// Generate bespoke illustrator-style artwork for the TCG mode's POKÉMON cards
// with Google's Gemini image model ("Nano Banana"), varying the art style
// across the roster the way real Pokémon TCG cards each have a different
// illustrator. Uses image-to-image: each card is seeded with its official
// artwork so the creature stays accurate, then restyled.
//
//   1. Restyle each Pokémon from its official artwork + a rotating style.
//   2. Upload the PNG to the public `tcg-art` bucket.
//   3. Record the URL in client/js/tcg/tcg-art.js (id → url), which the catalog
//      merges onto the card defs (full-bleed art) at load/build time.
//
// Idempotent: cards already in tcg-art.js are skipped unless you pass --force.
//
// Usage:
//   node scripts/generate-pokemon-art.js               # generate missing
//   node scripts/generate-pokemon-art.js --force       # regenerate all
//   node scripts/generate-pokemon-art.js fire-charizard  # one card id
//
// Env (.env): VEO_API_KEY (Gemini key), SUPABASE_URL, SUPABASE_SERVICE_KEY.

require("dotenv").config();
const fs = require("fs");
const path = require("path");

const { VEO_API_KEY, SUPABASE_URL, SUPABASE_SERVICE_KEY } = process.env;
if (!VEO_API_KEY) { console.error("Missing VEO_API_KEY in .env"); process.exit(1); }
if (!SUPABASE_URL || !SUPABASE_SERVICE_KEY) { console.error("Missing SUPABASE_URL / SUPABASE_SERVICE_KEY in .env"); process.exit(1); }

const GLA = "https://generativelanguage.googleapis.com/v1beta";
const MODEL = process.env.TCG_ART_MODEL || "gemini-2.5-flash-image";
const BUCKET = "tcg-art";
const OUT_JS = path.join(__dirname, "..", "client", "js", "tcg", "tcg-art.js");

// A spread of distinct Pokémon-illustrator styles, rotated across the roster.
const STYLES = [
  "soft watercolour wash with gentle pastel tones and visible paper texture",
  "bold cel-shaded anime with crisp clean linework and flat vibrant colour",
  "dramatic oil painting with rich impasto brushstrokes and deep shadows",
  "whimsical children's storybook illustration, warm and cosy",
  "dynamic shonen action manga with bold speed lines and high energy",
  "detailed semi-realistic digital painting with cinematic lighting",
  "retro 1990s holographic trading-card art with airbrushed gradients",
  "ukiyo-e Japanese woodblock print with flowing expressive linework",
  "moody atmospheric concept art with volumetric fog and rim lighting",
  "vibrant pop-art with bold outlines and halftone shading",
  "delicate ink-and-brush sumi-e with expressive negative space",
  "sparkling pastel kawaii style, cute bright and cheerful",
];

const args = process.argv.slice(2);
const FORCE = args.includes("--force");
const onlyId = args.find((a) => !a.startsWith("--"));

const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

function readArt() {
  try {
    const src = fs.readFileSync(OUT_JS, "utf8");
    const m = src.match(/export default (\{[\s\S]*\});?\s*$/);
    return m ? JSON.parse(m[1]) : {};
  } catch { return {}; }
}
function writeArt(obj) {
  const body = `// Auto-generated by scripts/generate-tcg-art.js & generate-pokemon-art.js —\n// illustrator-style art hosted on Supabase. Do not edit by hand.\nexport default ${JSON.stringify(obj, null, 2)};\n`;
  fs.writeFileSync(OUT_JS, body);
}

async function fetchSeed(url) {
  const res = await fetch(url);
  if (!res.ok) throw new Error(`seed ${res.status}`);
  const mimeType = res.headers.get("content-type") || "image/png";
  const data = Buffer.from(await res.arrayBuffer()).toString("base64");
  return { inlineData: { mimeType, data } };
}

async function restyle(card, style) {
  const seed = await fetchSeed(card.art);
  const prompt =
    `Redraw this Pokémon, ${card.name}, keeping its design, colours and proportions accurate and instantly recognizable, ` +
    `as a premium Pokémon Trading Card Game illustration in the style of ${style}. ` +
    `Give it a dynamic heroic pose in a full scene with a fitting ${(card.type || "nature")} environment background and dramatic lighting, highly detailed. ` +
    `No text, no typography, no card frame, no borders, no watermark, no logo.`;
  const res = await fetch(`${GLA}/models/${MODEL}:generateContent?key=${VEO_API_KEY}`, {
    method: "POST", headers: { "Content-Type": "application/json" },
    body: JSON.stringify({ contents: [{ parts: [{ text: prompt }, seed] }], generationConfig: { responseModalities: ["IMAGE"] } }),
  });
  const body = await res.json().catch(() => ({}));
  if (!res.ok) throw new Error(`imagegen ${res.status}: ${JSON.stringify(body).slice(0, 240)}`);
  const part = (body.candidates?.[0]?.content?.parts || []).find((p) => p.inlineData || p.inline_data);
  const out = part?.inlineData?.data || part?.inline_data?.data;
  if (!out) throw new Error(`no image: ${JSON.stringify(body).slice(0, 240)}`);
  return Buffer.from(out, "base64");
}

async function upload(id, buf) {
  const res = await fetch(`${SUPABASE_URL}/storage/v1/object/${BUCKET}/${id}.png`, {
    method: "POST",
    headers: { Authorization: `Bearer ${SUPABASE_SERVICE_KEY}`, apikey: SUPABASE_SERVICE_KEY, "Content-Type": "image/png", "x-upsert": "true" },
    body: buf,
  });
  if (!res.ok) throw new Error(`upload ${res.status}: ${(await res.text()).slice(0, 200)}`);
  return `${SUPABASE_URL}/storage/v1/object/public/${BUCKET}/${id}.png`;
}

async function main() {
  const { POKEMON } = await import("../client/js/tcg/catalog.js");
  const art = readArt();
  const cards = POKEMON.filter((c) => (onlyId ? c.id === onlyId : true));
  let i = 0;
  for (const card of cards) {
    const style = STYLES[i++ % STYLES.length];
    if (art[card.id] && !FORCE) { console.log(`[pkmn-art] skip ${card.id}`); continue; }
    console.log(`[pkmn-art] ${card.id} — ${style.split(",")[0]}…`);
    try {
      const buf = await restyle(card, style);
      const url = await upload(card.id, buf);
      art[card.id] = url;
      writeArt(art);
      console.log(`  ✓ ${card.id}`);
    } catch (err) {
      console.error(`  ✗ ${card.id}: ${err.message}`);
      await sleep(1500);
    }
  }
  console.log("[pkmn-art] done. Rebuild the client bundle.");
}

main().catch((e) => { console.error(e); process.exit(1); });
